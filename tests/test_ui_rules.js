'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const source = fs.readFileSync(path.join(__dirname, '../packages/luci-app-l2tp-ipsec-client/htdocs/luci-static/resources/view/l2tp-ipsec-client.js'), 'utf8');
const boundary = source.indexOf('return view.extend({');
const model = new Function('rpc', source.slice(0, boundary) + 'return {readRules,groupRules,ruleError,probeTarget};')({declare:()=>()=>{}});
const old = {routes:['10.20.0.0/16'],domains:['api.example.com'],domain_prefixes:['internal-'],domain_suffixes:['example.org']};
const entries = model.readRules(key=>old[key]);
assert.equal(entries.length, 4);
assert.deepEqual(model.groupRules(entries), old);
assert.equal(model.ruleError(entries, 'exact', 'API.EXAMPLE.COM', null), '这条规则已经存在。');
assert.equal(model.ruleError(entries, 'exact', 'API.EXAMPLE.COM', 1), true);
assert.notEqual(model.ruleError(entries, 'subnet', '0.0.0.0/0', null), true);
assert.equal(model.ruleError(entries, 'prefix', 'api.', null), true);
entries[0] = {type:'suffix',value:'new.example.com'};
entries.splice(1,1);
assert.deepEqual(model.groupRules(entries), {routes:[],domains:[],domain_prefixes:['internal-'],domain_suffixes:['new.example.com','example.org']});
assert.deepEqual(model.readRules(key=>({domains:'single.example.com'})[key]), [{type:'exact',value:'single.example.com'}]);
for (const value of ['10.20.0.1','intranet.example.com','localhost','']) assert.equal(model.probeTarget(value), true);
for (const value of ['999.0.0.1','https://example.com','host:80','host\nname']) assert.notEqual(model.probeTarget(value), true);
assert.notEqual(model.ruleError(Array.from({length:512},()=>({type:'exact',value:'example.com'})), 'prefix', 'api.', null), true);
console.log('统一规则列表读写、编辑、删除、重复与边界校验通过。');
